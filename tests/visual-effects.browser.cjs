// Run with Playwright available through NODE_PATH or PLAYWRIGHT_MODULE_PATH.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const path = require('node:path');
const bridge = fs.readFileSync(path.join(__dirname, '../src/bridge.js'), 'utf8');
const palette = {window:'#18181b',base:'#101014',button:'#202024',hover:'#232329',input:'#202024',selection:'#153c4d',text:'#f1f1f3',muted:'#aaaab3',border:'#35353b',accent:'#54ccf5',accentHover:'#8edfff',onAccent:'#101014',link:'#54ccf5'};
const visual = {icons:'thin',feed:'cards',focus:true,alerts:true,raids:true,subscriptions:true,mentions:true,duration:1};
const base = {enabled:true,palette,motion:true,density:'compact',panel:'twitchChat',visual,testPulse:''};
const fixture = `<!doctype html><html><body><div class="stream-chat"><header class="stream-chat-header" style="height:48px"><button data-a-target="chat-settings"><svg viewBox="0 0 24 24"><circle cx="12" cy="12" r="5"/></svg>Settings</button></header><div role="log"><div class="user-notice-line" data-msg-id="raid" data-id="existing">Historical raid</div><div class="chat-line__message"><span class="chat-author__display-name" style="color:red">User</span><span>Example message</span><img class="chat-image" alt="emote"></div></div><div class="chat-input"><textarea data-a-target="chat-input"></textarea><button data-a-target="emote-picker-button"><svg/></button><button data-a-target="chat-send-button">Send</button></div></div></body></html>`;
(async()=>{
 const browser = await chromium.launch({headless:true,...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {})});
 const page = await browser.newPage(); const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('https://www.twitch.tv/**',r=>r.fulfill({contentType:'text/html',body:fixture}));
 await page.route('https://dashboard.twitch.tv/**',r=>r.fulfill({contentType:'text/html',body:fixture}));
 await page.goto('https://www.twitch.tv/popout/example/chat');
 const run = config => page.evaluate(bridge.replace('__CONFIG__',JSON.stringify(config)));
 const event = () => page.locator('#obs-twitch-dock-themes-edge').getAttribute('data-event');
 const original = await page.locator('.chat-line__message').innerHTML();
 await run(base);
 assert.equal(await event(),null,'Historical notice triggered alert');
 assert.equal(await page.locator('.chat-line__message').innerHTML(),original,'Message DOM changed');
 assert.equal(await page.locator('.stream-chat-header').evaluate(el=>getComputedStyle(el).maxHeight),'10px');
 await page.locator('[data-a-target="chat-settings"]').focus();
 assert.equal(await page.locator('.stream-chat-header').evaluate(el=>getComputedStyle(el).opacity),'1','Keyboard could not reveal header');
 assert.ok(await page.locator('[data-a-target="chat-send-button"]').isVisible(),'Focus hid message sending');
 assert.equal(await page.locator('[data-a-target="chat-settings"] svg').evaluate(el=>getComputedStyle(el).visibility),'hidden');
 assert.ok((await page.locator('[data-a-target="chat-settings"]').evaluate(el=>getComputedStyle(el,'::after').maskImage)).includes('data:image/svg+xml'));
 await page.waitForTimeout(1600);
 await page.locator('[role="log"]').evaluate(el=>el.insertAdjacentHTML('beforeend','<div class="chat-line__message">Ordinary message</div>'));
 await page.waitForTimeout(50); assert.equal(await event(),null,'Ordinary message triggered alert');
 await page.locator('[role="log"]').evaluate(el=>el.insertAdjacentHTML('beforeend','<div class="user-notice-line" data-msg-id="raid" data-id="new-raid">New raid</div>'));
 await page.waitForTimeout(50); assert.equal(await event(),'raid');
 assert.equal(await page.locator('#obs-twitch-dock-themes-edge').evaluate(el=>getComputedStyle(el).pointerEvents),'none');
 await run({...base,visual:{...visual,raids:false}});
 assert.equal(await event(),null,'Disabling raid filter did not stop current alert');
 await run(base);
 await page.locator('[role="log"]').evaluate(el=>el.insertAdjacentHTML('beforeend','<div class="user-notice-line" data-msg-id="resub" data-id="new-sub">Subscription</div>'));
 await page.waitForTimeout(50); assert.equal(await event(),'subscription');
 await page.locator('[role="log"]').evaluate(el=>el.insertAdjacentHTML('beforeend','<div class="chat-line__message chat-line__message--mentioned" data-id="new-mention">Mention</div>'));
 await page.waitForTimeout(50); assert.equal(await event(),'mention');
 await run({...base,motion:false});
 assert.equal(await page.locator('#obs-twitch-dock-themes-edge').getAttribute('data-motion'),'false');
 await run({...base,testPulse:'one'}); assert.equal(await event(),'test');
 await page.waitForTimeout(1100); assert.equal(await event(),null,'Alert did not expire');
 await run({...base,testPulse:'one'}); assert.equal(await event(),null,'Periodic injection repeated test request');
 await run({...base,visual:{...visual,alerts:false,focus:false,icons:'native'}});
 assert.equal(await page.locator('#obs-twitch-dock-themes-edge').count(),0,'Overlay leaked after disable');
 assert.equal(await page.evaluate(()=>Object.hasOwn(window,'__obsTwitchDockThemeEffects')),false,'Observer state leaked');
 assert.equal(await page.locator('[data-a-target="chat-settings"] svg').evaluate(el=>getComputedStyle(el).visibility),'visible');
 await run({...base,testPulse:'one'});
 assert.equal(await event(),null,'Re-enabling replayed an old test pulse');
 await run({...base,enabled:false}); assert.equal(await page.locator('#obs-twitch-dock-themes-style').count(),0);
 await run(base); await page.evaluate(()=>history.pushState({},'', '/login')); await run(base);
 assert.equal(await page.locator('#obs-twitch-dock-themes-edge').count(),0,'Out-of-scope navigation retained alert observer');
 await page.goto('https://dashboard.twitch.tv/popout/u/example/stream-manager/activity-feed');
 await page.setContent('<div class="activity-list-layout"><div class="activity-base-list-item"><div><div class="activity-base-list-item__title"><p>Long event title</p></div><button>Action</button></div></div></div>');
 const feedBase={...base,panel:'twitchFeed'};
 const eventDom = await page.locator('.activity-base-list-item').innerHTML();
 await run(feedBase);
 assert.equal(await page.locator('.activity-base-list-item').evaluate(el=>getComputedStyle(el).borderLeftWidth),'3px');
 assert.equal(await page.locator('.activity-base-list-item').innerHTML(),eventDom,'Feed contents or actions were rewritten');
 for(const width of [200,600]){
  await page.setViewportSize({width,height:500});
  assert.ok(await page.locator('button').isVisible());
 }
 await run({...feedBase,visual:{...visual,feed:'native'}});
 assert.equal(await page.locator('.activity-base-list-item').evaluate(el=>getComputedStyle(el).borderLeftWidth),'0px');
 assert.equal(await page.locator('#obs-twitch-dock-themes-edge').count(),0,'Chat alert attached to feed');
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('PASS: control icons, focus keyboard access, cards restore, event filters, no history/ordinary-message alerts, expiry, cleanup, preset test nonce and preserved content.');
})().catch(e=>{console.error(e);process.exit(1)});
